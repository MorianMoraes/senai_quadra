const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const storage=new Map();
let source=fs.readFileSync(__dirname+'/app.js','utf8').replace(/app\(\);\s*$/,'');
const context=vm.createContext({structuredClone,Intl,Date,Math,Set,JSON,Array,String,Number,console,
  localStorage:{getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,v)},document:{},setTimeout:()=>{}});
vm.runInContext(source,context);
const run=code=>vm.runInContext(code,context);
run(`toast=()=>{};app=()=>{};closeModal=()=>{};session={userId:'u2'};`);
assert.equal(run('canCreateTournament()'),true);
assert.match(run('tournamentsView(currentUser())'),/newTournamentBtn/);
run(`session={userId:'u1'}`);assert.equal(run('canCreateTournament()'),false);
run(`session={userId:'u4'}`);assert.equal(run('canCreateTournament()'),false);
for(const role of ['aluno','professor','diretor'])assert.equal(run(`navItems('${role}').some(i=>i[0]==='notifications')`),false);
assert.equal(run(`shellView(currentUser()).includes('notifBtn')`),false);
run(`state.tournaments=[{id:'test',name:'Copa',date:addDays(3),createdBy:'u2',status:'inscricoes',teamIds:[],registrations:[],rounds:[]}];`);
assert.equal(run(`registerTeam('test','t1')`),false,'incomplete roster');
run(`state.teams[0].memberIds=['u4','u5','u6','u7','u8','u9'];`);
run(`session={userId:'u5'}`);assert.equal(run(`registerTeam('test','t1')`),false,'nonleader');
run(`session={userId:'u2'}`);assert.equal(run(`registerTeam('test','t1')`),false,'teacher cannot register another team');
run(`session={userId:'u4'};state.users.find(u=>u.id==='u9').suspended=true;`);
assert.equal(run(`registerTeam('test','t1')`),false,'suspended player');
run(`state.users.find(u=>u.id==='u9').suspended=false;state.teams[0].memberIds[5]='u5';`);
assert.equal(run(`registerTeam('test','t1')`),false,'duplicate player');
run(`state.teams[0].memberIds[5]='u2';`);assert.equal(run(`registerTeam('test','t1')`),false,'teacher is not a player');
run(`state.teams[0].memberIds[5]='u9';state.teams[0].memberIds.push('u2');`);
assert.equal(run(`registerTeam('test','t1')`),false,'seven players');
run(`state.teams[0].memberIds.pop();state.tournaments[0].date=addDays(-1);`);
assert.equal(run(`registerTeam('test','t1')`),false,'past date');
run(`state.tournaments[0].date=addDays(3);`);
assert.equal(run(`registerTeam('test','t1')`),true,'leader registers six students');
assert.equal(run(`registerTeam('test','t1')`),false,'duplicate registration');
assert.equal(run(`state.tournaments[0].registrations[0].memberIds===state.teams[0].memberIds`),false,'snapshot is independent');
assert.equal(JSON.parse(storage.get('senaiSportsDemoV1')).tournaments[0].registrations[0].memberIds.length,6);
run(`session={userId:'u5'};state.teams[1].memberIds=['u4','u5','u6','u7','u8','u9'];`);
assert.equal(run(`registerTeam('test','t2')`),false,'player cannot enter twice in the same tournament');
assert.match(run(`tournamentCard(state.tournaments[0])`),/6\/6 inscritos/);
// Exercise the create form and its submit handler without depending on browser globals.
run(`session={userId:'u2'};modal=()=>{};const fields={tournamentForm:{},tourName:{value:'Copa da escola'},tourDate:{value:addDays(5)}};document.getElementById=id=>fields[id];openTournamentModal();fields.tournamentForm.onsubmit({preventDefault(){}});`);
assert.equal(run(`state.tournaments.length`),2);
assert.equal(run(`state.tournaments[1].teamIds.length`),0,'no automatic enrollment from games');
assert.equal(run(`state.tournaments[1].status`),'inscricoes');
assert.equal(run(`state.tournaments[1].createdBy`),'u2');
run(`fields.tourName.value=' ';fields.tournamentForm.onsubmit({preventDefault(){}});`);assert.equal(run(`state.tournaments.length`),2,'blank name');
run(`fields.tourName.value='Nova copa';session={userId:'u4'};fields.tournamentForm.onsubmit({preventDefault(){}});`);
assert.equal(run(`state.tournaments.length`),2,'permission rechecked on submit');
// Confirm that enrolled rosters cannot be edited.
run(`let modalOpened=false;modal=()=>{modalOpened=true;};openRosterModal('t1');`);
assert.equal(run('modalOpened'),false);
const allowed=new Set(['#f2f2f7','#ffffff','#fff','#e8eef8','#1c1c1e','#636366','#e5e5ea','#003087','#002166','#1a7f37','#d4620a','#3a3a3c','#f47920','#004bb5','#fef3ea']);
for(const color of fs.readFileSync(__dirname+'/style.css','utf8').match(/#[0-9a-f]{3,8}\b/gi)||[])assert.ok(allowed.has(color.toLowerCase()),color+' must belong to the guide');
console.log('PASS: tournament creation, leader authorization, roster validation, duplicate protection, persistence, navigation and PDF palette.');
